"""Generate outputs/report.md from collected experiment results.

Combines results_registry.json + per-experiment JSONs into a readable report
with honest RESULT_PENDING markers.

Usage:
    python -m src.report.generate_report
"""

from __future__ import annotations

import glob
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
RESULTS = ROOT / "outputs" / "results"
TAB = ROOT / "outputs" / "tables"
REG = ROOT / "outputs" / "results_registry.json"


def fmt(v, nd=3):
    return "RESULT_PENDING" if v is None else f"{v:.{nd}f}"


def main() -> None:
    lines: list[str] = []
    lines.append("# TelecomTS — Root-Cause Localization Results Report\n")
    lines.append(f"_Generated by `src/report/generate_report.py` from files under `outputs/`._\n")
    lines.append(
        "> **Protocol note (G5, 2026-10-14):** this aggregate mixes pre- and\n"
        "> post-repair artefacts and is **not citable**. The split was repaired so\n"
        "> each Track-2 synthetic recording's `normal/...` background source follows\n"
        "> its injected twin into the same split; every model must be retrained on\n"
        "> the repaired split. The current, citable numbers are in\n"
        "> `docs/results_v3.md` and `outputs/tables/headline_v3.{md,csv}`; check a\n"
        "> record's `data_fingerprint` in `outputs/results_registry.json` before use.\n"
    )

    reg_data = json.load(open(REG)) if REG.exists() else []
    by_exp: dict[str, list[dict]] = {}
    for r in reg_data:
        by_exp.setdefault(r.get("experiment", "?"), []).append(r)

    # Subset breakdown (headline): template vs instance-varying detection + RCA
    lines.append("## Subset breakdown — template vs instance-varying (corrected split)\n")
    sub_fp = RESULTS / "subset_breakdown.json"
    audit_fp = RESULTS / "shortcut_audit.json"
    if sub_fp.exists():
        sb = json.loads(sub_fp.read_text())
        lines.append(
            f"Test n={sb['n_test']} ({sb['n_pos']} anomalous: "
            f"{sb['n_template']} template + {sb['n_instance_varying']} instance-varying; "
            f"{sb['n_neg']} normal). Detection is scored per anomaly family against the "
            "common normal pool (injected recordings are all-positive).\n"
        )
        lines.append("|model|subset|ROC-AUC|PR-AUC|F1-max|top-k RCA Jaccard|")
        lines.append("|---|---|---|---|---|---|")
        for model in ("tagn_baseline", "tagn_grl"):
            for label in ("template", "instance_varying"):
                b = sb[model][label]
                det = b["detection"]
                lines.append(
                    f"|{model}|{label}|{fmt(det.get('roc_auc'))}|{fmt(det.get('pr_auc'))}|"
                    f"{fmt(det.get('f1_max'))}|{fmt(b.get('rca_topk_jaccard'))}|"
                )
        lines.append("")
        if audit_fp.exists():
            au = json.loads(audit_fp.read_text())
            lines.append("**Input-free type-oracle RCA ceiling** (emit the true type's template):\n")
            lines.append("|subset|windows|types|oracle Jaccard|global-majority Jaccard|")
            lines.append("|---|---|---|---|---|")
            for s in au.get("test_subsets", []):
                lines.append(
                    f"|{s['subset']}|{s['n_windows']}|{s['n_types']}|"
                    f"{fmt(s['test_type_oracle_jaccard'])}|{fmt(s['test_global_majority_jaccard'])}|"
                )
            lines.append(
                "\nOn template windows the input-free oracle exceeds every trained model, "
                "i.e. reported RCA there is largely a type lookup "
                "(see `docs/benchmark_shortcut_audit.md`).\n"
            )
    else:
        lines.append("RESULT_PENDING (run `python3 scripts/subset_breakdown.py`).\n")
    fig_fp = ROOT / "outputs" / "figures" / "exp" / "shortcut_rca_subsets.png"
    if fig_fp.exists():
        lines.append("![oracle vs model RCA, and per-family detection]"
                     "(outputs/figures/exp/shortcut_rca_subsets.png)\n")

    # exp_001
    lines.append("## exp_001 — Classical baselines (seed 42)\n")
    f1 = RESULTS / "exp_001_classical_baselines.json"
    if f1.exists():
        d1 = json.loads(f1.read_text())
        lines.append("|model|ROC-AUC|PR-AUC|F1@best|TPR@FPR0.01|")
        lines.append("|---|---|---|---|---|")
        for k, v in d1.items():
            if isinstance(v, dict) and "roc_auc" in v:
                lines.append(f"|{k}|{fmt(v['roc_auc'])}|{fmt(v['pr_auc'])}|"
                             f"{fmt(v.get('f1_max'))}|{fmt(v.get('tpr_at_fpr_0.01'))}|")
        lines.append("")
        lines.append(f"- Type (XGB): acc **{fmt(d1['type_ml']['type_accuracy'])}**, "
                     f"macro-F1(seen) **{fmt(d1['type_ml']['type_macro_f1_seen'])}**")
        r = d1.get("rca", {})
        lines.append(f"- RCA Jaccard: recording-prior **{fmt(r.get('recording_prior', {}).get('jaccard_mean'))}** "
                     f"vs ML type-prior **{fmt(r.get('type_prior_ml', {}).get('jaccard_mean'))}** "
                     f"vs input-shift **{fmt(r.get('input_shift_topK', {}).get('jaccard_mean'))}**")
        lines.append("")
    else:
        lines.append("RESULT_PENDING (exp_001 not run in this session).\n")

    # exp_002
    lines.append("## exp_002 — Temporal-GNN (TAGN), corrected-scaler pilot\n")
    seeds = sorted(glob.glob(str(RESULTS / "exp_002_tagn_seed*.json")))
    if seeds:
        rows = []
        for fp in seeds:
            d = json.load(open(fp))
            # Older TAGN files used the invalid degenerate-IQR scaler. The
            # corrected pilot explicitly records this field; never mix the
            # two protocols in one headline table.
            if "pretrained" not in d:
                continue
            seed = Path(fp).stem.split("_")[-1].removeprefix("seed")
            a = d["test"].get("anomaly", {})
            t = d["test"].get("type", {})
            r = d["test"].get("rca", {})
            e = d["test"].get("early_warning", {})
            rows.append([seed, *[fmt(a.get(m)) for m in ("roc_auc", "pr_auc", "tpr_at_fpr_0.01")],
                         fmt(t.get("accuracy")), fmt(t.get("macro_f1_seen")),
                         fmt(r.get("type_template_jaccard")), fmt(r.get("topk_shift_jaccard")),
                         fmt(e.get("warning_before_onset_frac"))])
        if rows:
            lines.append("|seed|ROC-AUC|PR-AUC|TPR@1%|type acc|type F1|RCA Jacc(T)|RCA Jacc(topK)|EW before|")
            lines.append("|---|---|---|---|---|---|---|---|---|")
            for row in rows:
                lines.append("|" + "|".join(map(str, row)) + "|")
            # mean/std
            num = np_load_stats(rows)
            if num:
                lines.append(f"\n- mean±std PR-AUC = **{num['pr_mean']:.3f} ± {num['pr_std']:.3f}**, "
                             f"ROC = {num['roc_mean']:.3f} ± {num['roc_std']:.3f} (n={len(rows)} seeds)")
            lines.append("")
        else:
            lines.append("RESULT_PENDING (corrected-scaler TAGN pilot not run).\n")
    else:
        lines.append("RESULT_PENDING (exp_002 seeds sweep not finished).\n")

    # exp_009 fixed-weight hybrid
    lines.append("## exp_009 — TAGN + deterministic logistic hybrid\n")
    hybrid_fp = RESULTS / "exp_009_hybrid_seed42.json"
    if hybrid_fp.exists():
        hd = json.loads(hybrid_fp.read_text())
        lines.append(f"- Fixed TAGN logit weight: **{fmt(hd.get('tagn_weight'))}**\n")
        lines.append("|expert|ROC-AUC|PR-AUC|TPR@FPR0.01|\n|---|---|---|---|")
        for name, metrics in hd.get("test", {}).items():
            lines.append(f"|{name}|{fmt(metrics.get('roc_auc'))}|{fmt(metrics.get('pr_auc'))}|"
                         f"{fmt(metrics.get('tpr_at_fpr_0.01'))}|")
        lines.append("")
    else:
        lines.append("RESULT_PENDING (exp_009 hybrid not run).\n")

    # exp_003 ablations
    lines.append("## exp_003 — Ablations\n")
    abl = sorted(glob.glob(str(RESULTS / "exp_003_ablation_*.json")))
    if abl:
        lines.append("|variant|test PR-AUC|test ROC|type acc|EW before|epochs|")
        lines.append("|---|---|---|---|---|---|")
        for fp in abl:
            d = json.load(open(fp))
            name = Path(fp).name.removeprefix("exp_003_ablation_")[:-5]
            lines.append(f"|{name}|{fmt(d['test'].get('anomaly', {}).get('pr_auc'))}|"
                         f"{fmt(d['test'].get('anomaly', {}).get('roc_auc'))}|"
                         f"{fmt(d['test'].get('type', {}).get('accuracy'))}|"
                         f"{fmt(d['test'].get('early_warning', {}).get('warning_before_onset_frac'))}|"
                         f"{len(d['history'])}|")
        lines.append("")
    else:
        lines.append("RESULT_PENDING (exp_003 not run).\n")

    # exp_004 robustness
    lines.append("## exp_004 — Input robustness\n")
    for fp in sorted(glob.glob(str(RESULTS / "exp_004_robustness_seed*.json"))):
        d = json.load(open(fp))
        lines.append(f"### {Path(fp).name}")
        lines.append("|scenario|PR-AUC|ROC-AUC|")
        lines.append("|---|---|---|")
        for k, v in d.items():
            if isinstance(v, dict) and "pr_auc" in v:
                lines.append(f"|{k}|{fmt(v['pr_auc'])}|{fmt(v['roc_auc'])}|")
        lines.append("")
    if not glob.glob(str(RESULTS / "exp_004_robustness_seed*.json")):
        lines.append("RESULT_PENDING (exp_004 not run).\n")

    # exp_005 LORO
    lines.append("## exp_005 — Leave-recording-out (Setting II)\n")
    loro = sorted(glob.glob(str(RESULTS / "exp_005_loro_seed*.json")))
    if loro:
        for fp in loro:
            d = json.load(open(fp))
            lines.append(f"### {Path(fp).name}")
            lines.append("|fold|PR-AUC|ROC|type acc|rca jacc|")
            lines.append("|---|---|---|---|---|")
            for fl in d.get("folds", []):
                a = fl.get("test_anomaly", {})
                lines.append(f"|{fl['fold']}|{fmt(a.get('pr_auc'))}|{fmt(a.get('roc_auc'))}|"
                             f"{fmt(fl.get('test_type', {}).get('accuracy'))}|"
                             f"{fmt(fl.get('test_rca', {}).get('type_template_jaccard'))}|")
            lines.append("")
            lines.append(f"Aggregate: {json.dumps(d.get('aggregate', {}), indent=0)}\n")
    else:
        lines.append("RESULT_PENDING (exp_005 not run).\n")

    # exp_006/007
    lines.append("## Graph validation\n")
    graph_fp = ROOT / "data" / "processed" / "graph_validation.json"
    if graph_fp.exists():
        gd = json.loads(graph_fp.read_text())
        lines.append(
            f"- Within-prototype edge-mask stability: **{fmt(gd.get('prototype_stability_mean'))}**\n"
            f"- Directed-edge fraction: **{fmt(gd.get('prototype_directed_fraction_mean'))}**\n"
            f"- Held-out forward-direction win fraction: **{fmt(gd.get('direction_forward_wins_mean'))}**\n"
            f"- Interpretation: {gd.get('interpretation', 'predictive audit only')}\n"
        )
    else:
        lines.append("RESULT_PENDING (graph validation not run).\n")

    lines.append("## exp_006 / exp_007 — Explainability & early warning\n")
    for name, key in (("exp_006_explainability.json", "agreement_with_template"),
                      ("exp_007_early_warning.json", "early_warning_test")):
        fp = RESULTS / name
        if fp.exists():
            d = json.loads(fp.read_text())
            lines.append(f"- `{name}`: {json.dumps(d.get(key, {}))}\n")
        else:
            lines.append(f"- `{name}`: RESULT_PENDING\n")

    (ROOT / "outputs" / "report.md").write_text("\n".join(lines))
    print("wrote outputs/report.md")


def np_load_stats(rows):
    import numpy as np

    prs = [float(r[2]) for r in rows if r[2] != "RESULT_PENDING"]
    rocs = [float(r[1]) for r in rows if r[1] != "RESULT_PENDING"]
    if not prs:
        return None
    return {
        "pr_mean": float(np.mean(prs)), "pr_std": float(np.std(prs)),
        "roc_mean": float(np.mean(rocs)), "roc_std": float(np.std(rocs)),
    }


if __name__ == "__main__":
    main()
